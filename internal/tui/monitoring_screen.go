// monitoringScreen controls the Prometheus exporter: the service (on, off,
// at boot) and its settings, which are kept in GoNix's own configuration.
type monitoringScreen struct {
	deps Deps
	menu *simpleMenu
}

const (
	moEnable = iota
	moDisable
	moStart
	moStop
	moRestart
	moSettings
	moPreview
	moDashboard
	moUnit
)

func newMonitoringScreen(deps Deps) *monitoringScreen {
	return &monitoringScreen{deps: deps, menu: newSimpleMenu([]menuItem{
		{title: "Enable", desc: "install the systemd unit; start now and at every boot"},
		{title: "Disable", desc: "stop, and do not start at boot"},
		{title: "Start"},
		{title: "Stop"},
		{title: "Restart"},
		{title: "Change Settings", desc: "address, host filters, collectors, stub_status"},
		{title: "Preview Metrics", desc: "one scrape, as Prometheus would see it"},
		{title: "Save Grafana Dashboard", desc: "write the dashboard for these metrics to a file you choose"},
		{title: "View systemd Unit"},
	})}
}

func (s *monitoringScreen) Init() tea.Cmd { return nil }

func (s *monitoringScreen) Update(msg tea.Msg) (screen, tea.Cmd) {
	km, ok := msg.(tea.KeyMsg)
	if !ok {
		return s, nil
	}
	if s.menu.HandleKey(km) {
		return s, nil
	}
	switch km.String() {
	case "esc", "q":
		return s, navPop()
	case "enter":
		return s.run(s.menu.Selected())
	}
	return s, nil
}

func (s *monitoringScreen) run(choice int) (screen, tea.Cmd) {
	x, ctx := s.deps.Exporter, backgroundCtx()
	var err error
	var done string
	switch choice {
	case moEnable:
		err, done = x.Enable(ctx), "Exporter enabled and running."
	case moDisable:
		err, done = x.Disable(ctx), "Exporter stopped and disabled."
	case moStart:
		err, done = x.Start(ctx), "Exporter started."
	case moStop:
		err, done = x.Stop(ctx), "Exporter stopped."
	case moRestart:
		err, done = x.Restart(ctx), "Exporter restarted."
	case moSettings:
		return s.settingsWizard(), nil
	case moPreview:
		return s.preview()
	case moDashboard:
		return s.dashboardWizard(), nil
	case moUnit:
		return newViewerScreen(x.UnitName()+".service", x.Unit(), s), nil
	}
	if err != nil {
		return newResultScreen(s.deps, "Monitoring", false, err.Error(), newMonitoringScreen(s.deps)), nil
	}
	return newResultScreen(s.deps, "Monitoring", true, done, newMonitoringScreen(s.deps)), nil
}

func (s *monitoringScreen) preview() (screen, tea.Cmd) {
	ex := metrics.FromServices(&s.deps, Version)
	defer ex.Close()
	ctx, cancel := context.WithTimeout(backgroundCtx(), 30*time.Second)
	defer cancel()
	var b bytes.Buffer
	if err := ex.Write(ctx, &b, metrics.Filter{}, nil); err != nil {
		return newResultScreen(s.deps, "Monitoring", false, err.Error(), s), nil
	}
	return newViewerScreen("Metrics (traffic counters start at zero in a preview)", b.String(), s), nil
}

// dashboardWizard asks where to save the dashboard. It is generated by this
// very GoNix, so it always matches the metrics this version exports.
func (s *monitoringScreen) dashboardWizard() screen {
	wf := []wizardField{{
		Key: "path", Label: "File or folder to save the Grafana dashboard to (an older copy is replaced):",
		Kind: fieldText, Default: "./" + dashboard.FileName,
		Validate: func(v string) error {
			if strings.TrimSpace(v) == "" {
				return fmt.Errorf("enter a path")
			}
			return nil
		},
	}}
	return newWizard("Monitoring — Grafana Dashboard", wf, func(v map[string]string) (screen, tea.Cmd) {
		path, err := dashboard.Save(strings.TrimSpace(v["path"]))
		if err != nil {
			return newResultScreen(s.deps, "Monitoring", false, err.Error(), newMonitoringScreen(s.deps)), nil
		}
		if abs, err := filepath.Abs(path); err == nil {
			path = abs
		}
		return newResultScreen(s.deps, "Monitoring", true,
			"Dashboard saved to "+path+"\n\nImport it in Grafana: Dashboards, New, Import.", newMonitoringScreen(s.deps)), nil
	}, func() (screen, tea.Cmd) { return newMonitoringScreen(s.deps), nil })
}

func fields(v string) []string {
	return strings.FieldsFunc(v, func(r rune) bool { return r == ',' || r == ' ' })
}

func (s *monitoringScreen) settingsWizard() screen {
	m := s.deps.Config.Monitoring
	list := func(key, label string, cur []string, check func([]string) error) wizardField {
		return wizardField{Key: key, Label: label, Kind: fieldText, Default: strings.Join(cur, " "),
			Validate: func(v string) error {
				if check == nil {
					return nil
				}
				return check(fields(v))
			}}
	}
	hostCheck := func(v []string) error {
		return config.MonitoringConfig{Listen: m.Listen, StubStatus: m.StubStatus, Hosts: v}.Validate()
	}
	collCheck := func(v []string) error {
		return config.MonitoringConfig{Listen: m.Listen, StubStatus: m.StubStatus, Collectors: v}.Validate()
	}
	wf := []wizardField{
		{Key: "listen", Label: "Address /metrics is served on:", Kind: fieldText, Default: m.Listen,
			Validate: config.ValidListen},
		list("hosts", "Only these hosts (patterns like *.example.com, space separated; empty = all):", m.Hosts, hostCheck),
		list("exclude", "Leave out these hosts (patterns; empty = none):", m.ExcludeHosts, hostCheck),
		list("collectors", "Collectors ("+strings.Join(config.Collectors, ", ")+"; empty = all):", m.Collectors, collCheck),
		{Key: "ttl", Label: "Reuse slow results (certificates, backends, nginx -t) for:", Kind: fieldText, Default: m.CacheTTL.String(),
			Validate: func(v string) error {
				if d, err := time.ParseDuration(v); err != nil || d < 0 {
					return fmt.Errorf("use a duration such as 30s or 1m")
				}
				return nil
			}},
		{Key: "stub", Label: "Serve Nginx connection counters (stub_status, needs its module)?", Kind: fieldBool, BoolDefault: m.StubStatus.Enabled},
		{Key: "stublisten", Label: "stub_status address (local only):", Kind: fieldText, Default: m.StubStatus.Listen,
			Validate: config.ValidListen, ShowIf: func(v map[string]string) bool { return v["stub"] == "yes" }},
	}
	return newWizard("Monitoring — Settings", wf, func(v map[string]string) (screen, tea.Cmd) {
		n := m
		n.Listen, n.Hosts, n.ExcludeHosts, n.Collectors = v["listen"], fields(v["hosts"]), fields(v["exclude"]), fields(v["collectors"])
		if slices.Equal(n.Collectors, config.Collectors) {
			n.Collectors = nil
		}
		n.CacheTTL, _ = time.ParseDuration(v["ttl"])
		n.StubStatus.Enabled = v["stub"] == "yes"
		if v["stublisten"] != "" {
			n.StubStatus.Listen = v["stublisten"]
		}
		if err := s.deps.Exporter.Apply(backgroundCtx(), n); err != nil {
			return newResultScreen(s.deps, "Monitoring", false, err.Error(), newMonitoringScreen(s.deps)), nil
		}
		return newResultScreen(s.deps, "Monitoring", true, "Settings saved; a running exporter was restarted.", newMonitoringScreen(s.deps)), nil
	}, func() (screen, tea.Cmd) { return newMonitoringScreen(s.deps), nil })
}

func (s *monitoringScreen) View(width, height int) string {
	st := s.deps.Exporter.Status(backgroundCtx())
	m := s.deps.Config.Monitoring
	body := headerStyle.Render("Monitoring") + "\n"
	body += mutedStyle.Render("A Prometheus exporter for Grafana: certificates, backends, hosts, Nginx and traffic.") + "\n\n"
	dot := disabledDot
	if st.Active {
		dot = enabledDot
	}
	body += fmt.Sprintf("%s %s  (%s)\n", dot, strings.ToUpper(orDash(st.State)), st.Unit)
	body += fmt.Sprintf("   at boot: %v   unit: %s\n", st.Enabled, map[bool]string{true: "installed", false: "not installed"}[st.Installed])
	body += fmt.Sprintf("   %s\n", st.URL)
	body += fmt.Sprintf("   hosts: %s   exclude: %s\n", joinOr(m.Hosts, "all"), joinOr(m.ExcludeHosts, "none"))
	body += fmt.Sprintf("   collectors: %s   cache: %s   stub_status: %v\n", joinOr(m.Collectors, "all"), m.CacheTTL, m.StubStatus.Enabled)
	if st.UnitStale {
		body += errorBoxStyle.Render("The systemd unit is out of date (GoNix moved?). Restart rewrites it.") + "\n"
	}
	body += "\n"
	body += s.menu.ViewFit(body, height)
	help := [][2]string{{"↑↓", "Navigate"}, {"Enter", "Select"}, {"Esc", "Back"}}
	return renderFrame(width, height, "GONIX", body, help)
}

func orDash(s string) string {
	if s == "" {
		return "-"
	}
	return s
}

func joinOr(v []string, empty string) string {
	if len(v) == 0 {
		return empty
	}
	return strings.Join(v, ", ")
}
